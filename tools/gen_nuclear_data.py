#!/usr/bin/env python3
"""Generate examples/materials/*.js data modules from an OpenMC checkout.

Reads (no OpenMC import needed):
  openmc/data/data.py                    natural abundances, Avogadro constant
  openmc/data/mass_1.mas20.txt           AME2020 atomic masses (+ element symbols)
  openmc/data/thermal.py                 thermal scattering table names
  openmc/data/material_libraries/*.json  material compendium (PNNL)

Usage: python3 tools/gen_nuclear_data.py [path/to/openmc]   (default: knowledge/openmc)
"""

import ast
import itertools
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OPENMC = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "knowledge" / "openmc"
DATA = OPENMC / "openmc" / "data"
OUT = ROOT / "examples" / "materials"


def assigned_literal(source, name):
    """Value of a top-level `name = <literal>` assignment."""
    for node in ast.parse(source).body:
        if isinstance(node, ast.Assign) and any(getattr(t, "id", None) == name for t in node.targets):
            return ast.literal_eval(node.value)
    raise KeyError(name)


data_py = (DATA / "data.py").read_text()
abundance = assigned_literal(data_py, "NATURAL_ABUNDANCE")
avogadro = assigned_literal(data_py, "AVOGADRO")

# AME2020, parsed like openmc.data.atomic_mass.
masses, symbols = {}, {}
with open(DATA / "mass_1.mas20.txt") as f:
    for line in itertools.islice(f, 36, None):
        z, a, sym = int(line[11:14]), int(line[16:19]), line[20:22].strip()
        masses[f"{sym}{a}".lower()] = float(line[106:109]) + 1e-6 * float(line[110:116] + "." + line[117:123])
        if z > 0:
            symbols[z] = sym
# "Natural" nuclides found in some libraries (e.g. C0): abundance-weighted mass.
for el in ["C", "Zn", "Pt", "Os", "Tl", "V"]:
    iso = [(n, x) for n, x in abundance.items() if re.fullmatch(rf"{el}\d+", n)]
    masses[f"{el}0".lower()] = sum(x * masses[n.lower()] for n, x in iso)

thermal_src = (DATA / "thermal.py").read_text()
block = re.search(r"_THERMAL_NAMES\s*=\s*\{(.*?)\n\}", thermal_src, re.S).group(1)
thermal = sorted(set(re.findall(r"'(c_[A-Za-z0-9_]+)'", block)))

OUT.mkdir(parents=True, exist_ok=True)
header = "// Generated by tools/gen_nuclear_data.py from OpenMC ({}). Do not edit.\n"
(OUT / "nuclear-data.js").write_text(
    header.format("openmc/data: data.py, mass_1.mas20.txt (AME2020), thermal.py")
    + f"export const AVOGADRO = {avogadro!r};\n"
    + "/** Element symbols by atomic number. */\n"
    + f"export const SYMBOLS = {json.dumps([symbols.get(z, '') for z in range(max(symbols) + 1)])};\n"
    + "/** Natural isotopic abundances (atom fractions). */\n"
    + f"export const NATURAL_ABUNDANCE = {json.dumps(abundance, separators=(',', ':'))};\n"
    + "/** Atomic masses in amu, keyed by lower-case nuclide name. */\n"
    + f"export const MASSES = {json.dumps({k: round(v, 9) for k, v in masses.items()}, separators=(',', ':'))};\n"
    + "/** Thermal scattering (S(a,b)) table names known to OpenMC. */\n"
    + f"export const THERMAL_NAMES = {json.dumps(thermal)};\n"
)

for lib in sorted((DATA / "material_libraries").glob("*.json")):
    content = json.loads(lib.read_text())
    (OUT / f"{lib.stem}.js").write_text(
        header.format(f"openmc/data/material_libraries/{lib.name}")
        + f"export default {json.dumps(content, separators=(',', ':'))};\n"
    )

print(f"{len(abundance)} abundances, {len(masses)} masses, {len(symbols)} elements, {len(thermal)} thermal names")
